interface WatermarkEntry {
	readonly id: string;
	readonly text: string;
	readonly when?: {
		native?: ContextKeyExpression;
		web?: ContextKeyExpression;
	};
}

const showChatContextKey = ContextKeyExpr.and(ContextKeyExpr.equals('chatSetupHidden', false), ContextKeyExpr.equals('chatSetupDisabledInWorkspace', false));

const openChat: WatermarkEntry = { text: localize('watermark.openChat', "Open Chat"), id: 'workbench.action.chat.open', when: { native: showChatContextKey, web: showChatContextKey } };
const showCommands: WatermarkEntry = { text: localize('watermark.showCommands', "Show All Commands"), id: 'workbench.action.showCommands' };
const gotoFile: WatermarkEntry = { text: localize('watermark.quickAccess', "Go to File"), id: 'workbench.action.quickOpen' };
const openFile: WatermarkEntry = { text: localize('watermark.openFile', "Open File"), id: 'workbench.action.files.openFile' };
const openFolder: WatermarkEntry = { text: localize('watermark.openFolder', "Open Folder"), id: 'workbench.action.files.openFolder' };
const openFileOrFolder: WatermarkEntry = { text: localize('watermark.openFileFolder', "Open File or Folder"), id: 'workbench.action.files.openFileFolder' };
const openRecent: WatermarkEntry = { text: localize('watermark.openRecent', "Open Recent"), id: 'workbench.action.openRecent' };
const newUntitledFile: WatermarkEntry = { text: localize('watermark.newUntitledFile', "New Untitled Text File"), id: 'workbench.action.files.newUntitledFile' };
const findInFiles: WatermarkEntry = { text: localize('watermark.findInFiles', "Find in Files"), id: 'workbench.action.findInFiles' };
const toggleTerminal: WatermarkEntry = { text: localize({ key: 'watermark.toggleTerminal', comment: ['toggle is a verb here'] }, "Toggle Terminal"), id: 'workbench.action.terminal.toggleTerminal', when: { web: ContextKeyExpr.equals('terminalProcessSupported', true) } };
const startDebugging: WatermarkEntry = { text: localize('watermark.startDebugging', "Start Debugging"), id: 'workbench.action.debug.start', when: { web: ContextKeyExpr.equals('terminalProcessSupported', true) } };
const openSettings: WatermarkEntry = { text: localize('watermark.openSettings', "Open Settings"), id: 'workbench.action.openSettings' };

const baseEntries: WatermarkEntry[] = [
	openChat,
	showCommands,
];

const emptyWindowEntries: WatermarkEntry[] = coalesce([
	...baseEntries,
	openRecent,
	...(isMacintosh && !isWeb ? [openFileOrFolder] : [openFile, openFolder]),
	isMacintosh && !isWeb ? newUntitledFile : undefined, // fill in one more on macOS to get to 5 entries
]);

const workspaceEntries: WatermarkEntry[] = [
	...baseEntries,
];

const otherEntries: WatermarkEntry[] = [
	gotoFile,
	findInFiles,
	startDebugging,
	toggleTerminal,
	openSettings,
];

export class EditorGroupWatermark extends Disposable {

	private static readonly CACHED_WHEN = 'editorGroupWatermark.whenConditions';
	private static readonly SETTINGS_KEY = 'workbench.tips.enabled';
	private static readonly MINIMUM_ENTRIES = 3;

	private readonly cachedWhen: { [when: string]: boolean };

	private readonly shortcuts: HTMLElement;
	private readonly transientDisposables = this._register(new DisposableStore());
	private readonly keybindingLabels = this._register(new DisposableStore());

	private enabled = false;
	private workbenchState: WorkbenchState;

	constructor(
		container: HTMLElement,
		@IKeybindingService private readonly keybindingService: IKeybindingService,
		@IWorkspaceContextService private readonly contextService: IWorkspaceContextService,
		@IContextKeyService private readonly contextKeyService: IContextKeyService,
		@IConfigurationService private readonly configurationService: IConfigurationService,
		@IStorageService private readonly storageService: IStorageService,
		@ICommandService private readonly commandService: ICommandService,
		@IWorkbenchEnvironmentService private readonly environmentService: IWorkbenchEnvironmentService
	) {
		super();

		this.cachedWhen = this.storageService.getObject(EditorGroupWatermark.CACHED_WHEN, StorageScope.PROFILE, Object.create(null));
		this.workbenchState = this.contextService.getWorkbenchState();

		if (this.environmentService.isSessionsWindow) {
			this.shortcuts = document.createElement('div');
			return;
		}

		const runCommand = (command: string, ...args: unknown[]) => {
			Promise.resolve(this.commandService.executeCommand(command, ...args)).catch(onUnexpectedError);
		};

		const createActionRow = (icon: string, label: string, command: string, ...args: unknown[]) => {
			const keybinding = this.keybindingService.lookupKeybinding(command)?.getLabel();
			const row = $('button.backboard-empty-welcome-action', { type: 'button' },
				$('span.backboard-empty-welcome-action-icon.codicon.' + icon, { 'aria-hidden': 'true' }),
				$('span.backboard-empty-welcome-action-label', {}, label),
				keybinding ? $('span.backboard-empty-welcome-action-keybinding', {}, keybinding) : $('span.backboard-empty-welcome-action-keybinding', {}),
			) as HTMLButtonElement;
			this._register(addDisposableListener(row, 'click', () => runCommand(command, ...args)));
			return row;
		};

		const createSection = (label: string, ...actions: HTMLElement[]) => $('.backboard-empty-welcome-section', {},
			$('.backboard-empty-welcome-section-heading', {},
				$('span', {}, label),
				$('.backboard-empty-welcome-section-rule'),
			),
			$('.backboard-empty-welcome-action-list', {}, ...actions),
		);

		const returnToOnboarding = $('button.backboard-empty-welcome-footer-link', { type: 'button' }, localize('watermark.backboardReturnToOnboarding', "Return to Onboarding")) as HTMLButtonElement;
		this._register(addDisposableListener(returnToOnboarding, 'click', () => runCommand('workbench.action.welcomeOnboarding2026')));

		const root = $('.editor-group-watermark');
		const containerElement = append(root, $('.watermark-container'));
		append(containerElement, $('.backboard-empty-welcome', {},
			$('.backboard-empty-welcome-header', {},
				$('.backboard-empty-welcome-logo', { 'aria-hidden': 'true' }),
				$('.backboard-empty-welcome-header-copy', {},
					$('h1.backboard-empty-welcome-title', {}, localize('watermark.backboardWelcomeTitle', "Welcome to Backboard Studio")),
					$('p.backboard-empty-welcome-subtitle', {}, localize('watermark.backboardWelcomeSubtitle', "The editor for what's next")),
				),
			),
			createSection(
				localize('watermark.backboardGetStarted', "GET STARTED"),
				createActionRow('codicon-add', localize('watermark.backboardNewFile', "New File"), 'workbench.action.files.newUntitledFile'),
				createActionRow('codicon-folder-opened', localize('watermark.backboardOpenProject', "Open Project"), 'workbench.action.files.openFolder'),
				createActionRow('codicon-cloud-download', localize('watermark.backboardCloneRepository', "Clone Repository"), 'git.clone'),
			),
			createSection(
				localize('watermark.backboardConfigure', "CONFIGURE"),
				createActionRow('codicon-settings-gear', localize('watermark.backboardOpenSettings', "Open Settings"), 'workbench.action.openSettings'),
				createActionRow('codicon-keyboard', localize('watermark.backboardCustomizeKeymaps', "Customize Keymaps"), 'workbench.action.openGlobalKeybindings'),
				createActionRow('codicon-extensions', localize('watermark.backboardExploreExtensions', "Explore Extensions"), 'workbench.view.extensions'),
			),
			returnToOnboarding,
		));
		const shortcuts = append(containerElement, $('.shortcuts'));

		append(container, root);
		this.shortcuts = shortcuts;

		this.registerListeners();

		this.render();
	}

	private registerListeners(): void {
		this._register(this.configurationService.onDidChangeConfiguration(e => {
			if (
				e.affectsConfiguration(EditorGroupWatermark.SETTINGS_KEY) &&
				this.enabled !== this.configurationService.getValue<boolean>(EditorGroupWatermark.SETTINGS_KEY)
			) {
				this.render();
			}
		}));

		this._register(this.contextService.onDidChangeWorkbenchState(workbenchState => {
			if (this.workbenchState !== workbenchState) {
				this.workbenchState = workbenchState;
				this.render();
			}
		}));

		this._register(this.storageService.onWillSaveState(e => {
			if (e.reason === WillSaveStateReason.SHUTDOWN) {
				const entries = [...emptyWindowEntries, ...workspaceEntries, ...otherEntries];
				for (const entry of entries) {
					const when = isWeb ? entry.when?.web : entry.when?.native;
					if (when) {
						this.cachedWhen[entry.id] = this.contextKeyService.contextMatchesRules(when);
					}
				}

				this.storageService.store(EditorGroupWatermark.CACHED_WHEN, JSON.stringify(this.cachedWhen), StorageScope.PROFILE, StorageTarget.MACHINE);
			}
		}));
	}

	private render(): void {
		this.enabled = this.configurationService.getValue<boolean>(EditorGroupWatermark.SETTINGS_KEY);

		clearNode(this.shortcuts);
		this.transientDisposables.clear();

		if (!this.enabled || this.environmentService.isSessionsWindow) {
			return;
		}

		const entries = this.filterEntries(this.workbenchState !== WorkbenchState.EMPTY ? workspaceEntries : emptyWindowEntries);
		if (entries.length < EditorGroupWatermark.MINIMUM_ENTRIES) {
			const additionalEntries = this.filterEntries(otherEntries);
			shuffle(additionalEntries);
			entries.push(...additionalEntries.slice(0, EditorGroupWatermark.MINIMUM_ENTRIES - entries.length));
		}

		const box = append(this.shortcuts, $('.watermark-box'));

		const update = () => {
			clearNode(box);
			this.keybindingLabels.clear();

			for (const entry of entries) {
				const keys = this.keybindingService.lookupKeybinding(entry.id);
				if (!keys) {
					continue;
				}

				const dl = append(box, $('dl'));
				const dt = append(dl, $('dt'));
				dt.textContent = entry.text;

				const dd = append(dl, $('dd'));

				const label = this.keybindingLabels.add(new KeybindingLabel(dd, OS, { renderUnboundKeybindings: true, ...defaultKeybindingLabelStyles }));
				label.set(keys);
			}
		};

		update();
		this.transientDisposables.add(this.keybindingService.onDidUpdateKeybindings(update));
	}

	private filterEntries(entries: WatermarkEntry[]): WatermarkEntry[] {
		const filteredEntries = entries
			.filter(entry => {
				if (this.cachedWhen[entry.id]) {
					return true; // cached from previous session
				}

				const contextKey = isWeb ? entry.when?.web : entry.when?.native;
				return !contextKey /* works without context */ || this.contextKeyService.contextMatchesRules(contextKey);
			})
			.filter(entry => !!CommandsRegistry.getCommand(entry.id))
			.filter(entry => !!this.keybindingService.lookupKeybinding(entry.id));

		return filteredEntries;
	}
}
